#!/usr/bin/env node
// Generates Luau config modules from the browser game's shared TypeScript data.
//
// READ-ONLY with respect to the web game: this script only *reads*
//   ../shared/weapons.ts and ../shared/cards.ts
// and writes into ./src/shared/ of the Roblox project.
//
// Usage:
//   node tools/gen-config.mjs          -> (re)generate WeaponsConfig.luau + CardsConfig.luau
//   node tools/gen-config.mjs --check  -> exit 1 if committed files differ from fresh output

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const robloxRoot = resolve(here, '..');
const webShared = resolve(robloxRoot, '..', 'shared');
const outDir = resolve(robloxRoot, 'src', 'shared');
const checkMode = process.argv.includes('--check');

/** Extracts the literal that follows `export const <name>...=` and evaluates it as plain data. */
function extractLiteral(source, constName, open, close) {
  const declIdx = source.indexOf(`export const ${constName}`);
  if (declIdx < 0) throw new Error(`Cannot find export const ${constName}`);
  const eqIdx = source.indexOf('=', declIdx);
  const start = source.indexOf(open, eqIdx);
  // Walk to matching bracket, ignoring brackets inside strings and comments.
  let depth = 0;
  let i = start;
  let inStr = null;
  for (; i < source.length; i++) {
    const ch = source[i];
    const next = source[i + 1];
    if (inStr) {
      if (ch === '\\') { i++; continue; }
      if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === '/' && next === '/') { i = source.indexOf('\n', i); continue; }
    if (ch === '/' && next === '*') { i = source.indexOf('*/', i) + 1; continue; }
    if (ch === "'" || ch === '"' || ch === '`') { inStr = ch; continue; }
    if (ch === open) depth++;
    else if (ch === close) {
      depth--;
      if (depth === 0) break;
    }
  }
  const literal = source.slice(start, i + 1);
  // eslint-disable-next-line no-new-func
  return new Function(`"use strict"; return (${literal});`)();
}

const WEAPON_KEYS = [
  'id', 'name', 'damage', 'fireRate', 'clipSize', 'maxReserve', 'reloadTime', 'spread',
  'bulletSpeed', 'pellets', 'burstCount', 'bounceCount', 'bulletRadius', 'explosiveRadius',
  'pierceCount', 'color',
];
const WEAPON_IGNORED = new Set(['cost', 'ammoCost']);
const CARD_KEYS = ['id', 'name', 'rarity', 'category', 'description'];
const STAT_KEYS = [
  'bonusDamagePct', 'bonusFireRatePct', 'bonusClipPct', 'extraPellets', 'burstCount', 'pierceBonus',
  'bounceCount', 'explosiveRadiusPct', 'bulletSpeedPct', 'bulletSizePct', 'spreadModifierPct',
  'lifestealPct', 'maxHpPct', 'hpRegenPct', 'damageReductionPct', 'moveSpeedPct',
  'dashCooldownReductionPct', 'reloadTimeReductionPct', 'hasFreeze', 'hasTesla', 'grantWeapon',
];

function luaValue(v) {
  if (typeof v === 'string') return JSON.stringify(v); // JSON string escapes are valid Luau escapes
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`Non-finite number ${v}`);
    return String(v);
  }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  throw new Error(`Unsupported value type: ${typeof v}`);
}

function assertKnownKeys(obj, allowed, ignored, ctx) {
  for (const k of Object.keys(obj)) {
    if (!allowed.includes(k) && !(ignored && ignored.has(k)) && k !== 'stats') {
      throw new Error(`${ctx}: unknown key "${k}" (source schema changed?)`);
    }
  }
}

function genWeapons() {
  const src = readFileSync(resolve(webShared, 'weapons.ts'), 'utf8');
  const weapons = extractLiteral(src, 'WEAPONS', '{', '}');
  const ids = Object.keys(weapons);
  const lines = [];
  lines.push('--!strict');
  lines.push('-- AUTO-GENERATED by tools/gen-config.mjs from ../shared/weapons.ts. DO NOT EDIT BY HAND.');
  lines.push('-- Values are in WEB UNITS; StatCalculator converts to studs.');
  lines.push('local Types = require(script.Parent.Types)');
  lines.push('');
  lines.push('local WeaponsConfig: { [string]: Types.WeaponDef } = {');
  for (const id of ids) {
    const w = weapons[id];
    assertKnownKeys(w, WEAPON_KEYS, WEAPON_IGNORED, `weapon ${id}`);
    if (w.id !== id) throw new Error(`weapon key ${id} != id ${w.id}`);
    lines.push(`\t${id} = {`);
    for (const k of WEAPON_KEYS) {
      if (w[k] !== undefined) lines.push(`\t\t${k} = ${luaValue(w[k])},`);
    }
    lines.push('\t},');
  }
  lines.push('}');
  lines.push('');
  lines.push(`-- Stable iteration order (matches source order)`);
  lines.push(`local ORDER: { string } = { ${ids.map((i) => JSON.stringify(i)).join(', ')} }`);
  lines.push('');
  lines.push('return table.freeze({');
  lines.push('\tbyId = WeaponsConfig,');
  lines.push('\torder = ORDER,');
  lines.push('})');
  lines.push('');
  return { text: lines.join('\n'), count: ids.length };
}

function genCards() {
  const src = readFileSync(resolve(webShared, 'cards.ts'), 'utf8');
  const cards = extractLiteral(src, 'ROUNDS_CARDS', '[', ']');
  const seen = new Set();
  const lines = [];
  lines.push('--!strict');
  lines.push('-- AUTO-GENERATED by tools/gen-config.mjs from ../shared/cards.ts. DO NOT EDIT BY HAND.');
  lines.push('local Types = require(script.Parent.Types)');
  lines.push('');
  lines.push('local LIST: { Types.CardDef } = {');
  for (const c of cards) {
    assertKnownKeys(c, CARD_KEYS, null, `card ${c.id}`);
    if (seen.has(c.id)) throw new Error(`duplicate card id ${c.id}`);
    seen.add(c.id);
    lines.push('\t{');
    for (const k of CARD_KEYS) lines.push(`\t\t${k} = ${luaValue(c[k])},`);
    const stats = c.stats || {};
    for (const k of Object.keys(stats)) {
      if (!STAT_KEYS.includes(k)) throw new Error(`card ${c.id}: unknown stat "${k}"`);
    }
    const parts = STAT_KEYS.filter((k) => stats[k] !== undefined).map((k) => `${k} = ${luaValue(stats[k])}`);
    lines.push(`\t\tstats = { ${parts.join(', ')} },`);
    lines.push('\t},');
  }
  lines.push('}');
  lines.push('');
  lines.push('local BY_ID: { [string]: Types.CardDef } = {}');
  lines.push('for _, card in LIST do');
  lines.push('\tBY_ID[card.id] = card');
  lines.push('end');
  lines.push('');
  lines.push('return table.freeze({');
  lines.push('\tlist = LIST,');
  lines.push('\tbyId = BY_ID,');
  lines.push(`\tcount = ${cards.length},`);
  lines.push('})');
  lines.push('');
  return { text: lines.join('\n'), count: cards.length };
}

const outputs = [
  ['WeaponsConfig.luau', genWeapons()],
  ['CardsConfig.luau', genCards()],
];

let mismatch = false;
for (const [file, { text, count }] of outputs) {
  const path = resolve(outDir, file);
  if (checkMode) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error(`MISMATCH: ${file} is out of date with web source (${count} entries)`);
      mismatch = true;
    } else {
      console.log(`OK: ${file} matches web source (${count} entries)`);
    }
  } else {
    writeFileSync(path, text, 'utf8');
    console.log(`Wrote ${file} (${count} entries)`);
  }
}
if (mismatch) process.exit(1);
